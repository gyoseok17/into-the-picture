CREATE TABLE photo_map_location_representative (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                     BIGINT NOT NULL,
    location_key                VARCHAR(128) NOT NULL,
    representative_photo_id     BIGINT NULL,
    created_at                  TIMESTAMP NULL,
    updated_at                  TIMESTAMP NULL,
    CONSTRAINT fk_photo_map_location_representative_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_photo_map_location_representative_photo
        FOREIGN KEY (representative_photo_id) REFERENCES photo_record (id) ON DELETE SET NULL,
    CONSTRAINT uk_photo_map_location_representative_user_location
        UNIQUE (user_id, location_key)
);
