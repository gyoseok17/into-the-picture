CREATE TABLE photo_record (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL,
    user_photo_id     BIGINT NOT NULL,
    contest_id        BIGINT NULL,
    taken_at          TIMESTAMP NULL,
    place_name        VARCHAR(255) NULL,
    memo              VARCHAR(500) NULL,
    display_mode      VARCHAR(20) NOT NULL DEFAULT 'PHOTO_ONLY',
    archived_at       TIMESTAMP NULL,
    contest_linked_at TIMESTAMP NULL,
    created_at        TIMESTAMP NULL,
    updated_at        TIMESTAMP NULL,
    CONSTRAINT fk_photo_record_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_photo_record_photo FOREIGN KEY (user_photo_id) REFERENCES user_photo (id),
    CONSTRAINT fk_photo_record_contest FOREIGN KEY (contest_id) REFERENCES contest_work (id),
    CONSTRAINT ck_photo_record_display_mode CHECK (display_mode IN ('PHOTO_ONLY', 'WITH_CONTEST')),
    CONSTRAINT ck_photo_record_contest_mode CHECK (display_mode <> 'WITH_CONTEST' OR contest_id IS NOT NULL)
);

-- Every existing upload becomes one private album record.
INSERT INTO photo_record (user_id, user_photo_id, taken_at, memo, display_mode, created_at, updated_at)
SELECT user_id, id, taken_at, memo, 'PHOTO_ONLY', created_at, updated_at
FROM user_photo;

-- Existing comparison rows enrich their matching photo record. The current UI prevents duplicates.
UPDATE photo_record record
SET contest_id = comparison.contest_id,
    display_mode = 'WITH_CONTEST',
    contest_linked_at = comparison.created_at,
    updated_at = comparison.updated_at
FROM photo_comparison comparison
WHERE record.user_photo_id = comparison.user_photo_id
  AND record.user_id = comparison.user_id
  AND NOT EXISTS (
      SELECT 1
      FROM photo_comparison earlier
      WHERE earlier.user_photo_id = comparison.user_photo_id
        AND earlier.user_id = comparison.user_id
        AND earlier.id < comparison.id
  );

-- Preserve any legacy duplicate comparison as a separate record instead of discarding history.
INSERT INTO photo_record (user_id, user_photo_id, contest_id, display_mode, contest_linked_at, created_at, updated_at)
SELECT comparison.user_id, comparison.user_photo_id, comparison.contest_id, 'WITH_CONTEST', comparison.created_at, comparison.created_at, comparison.updated_at
FROM photo_comparison comparison
WHERE EXISTS (
    SELECT 1
    FROM photo_comparison earlier
    WHERE earlier.user_photo_id = comparison.user_photo_id
      AND earlier.user_id = comparison.user_id
      AND earlier.id < comparison.id
);

CREATE INDEX idx_photo_record_user_active_time ON photo_record (user_id, archived_at, taken_at DESC, created_at DESC);
CREATE INDEX idx_photo_record_user_active_place ON photo_record (user_id, archived_at, place_name);
CREATE INDEX idx_photo_record_user_contest ON photo_record (user_id, contest_id);

ALTER TABLE user_photo DROP COLUMN taken_at;
ALTER TABLE user_photo DROP COLUMN memo;
DROP TABLE photo_comparison;
