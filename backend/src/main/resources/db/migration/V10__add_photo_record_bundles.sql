CREATE TABLE photo_record_bundle (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    taken_at        TIMESTAMP NULL,
    place_name      VARCHAR(255) NULL,
    map_region_code VARCHAR(32) NULL,
    map_city_code   VARCHAR(48) NULL,
    memo            VARCHAR(500) NULL,
    archived_at     TIMESTAMP NULL,
    created_at      TIMESTAMP NULL,
    updated_at      TIMESTAMP NULL,
    CONSTRAINT fk_photo_record_bundle_user FOREIGN KEY (user_id) REFERENCES users (id)
);

ALTER TABLE photo_record ADD COLUMN bundle_id BIGINT NULL;
ALTER TABLE photo_record ADD CONSTRAINT fk_photo_record_bundle
    FOREIGN KEY (bundle_id) REFERENCES photo_record_bundle (id);

CREATE INDEX idx_photo_record_bundle_user_active_time
    ON photo_record_bundle (user_id, archived_at, taken_at DESC, created_at DESC);
CREATE INDEX idx_photo_record_bundle_record ON photo_record (bundle_id, created_at ASC);
