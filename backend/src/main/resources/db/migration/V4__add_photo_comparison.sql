CREATE TABLE photo_comparison (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL,
    user_photo_id BIGINT NOT NULL,
    contest_id    BIGINT NOT NULL,
    created_at    TIMESTAMP NULL,
    updated_at    TIMESTAMP NULL,
    CONSTRAINT fk_photo_comparison_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_photo_comparison_photo FOREIGN KEY (user_photo_id) REFERENCES user_photo (id),
    CONSTRAINT fk_photo_comparison_contest FOREIGN KEY (contest_id) REFERENCES contest_work (id)
);

CREATE INDEX idx_photo_comparison_user_created ON photo_comparison (user_id, created_at DESC);
